"""Standard computed block for chart files in data/charts/.

Every chart file keeps its human sections (intake, verification log, readings, notes) and one machine
section, "computed", which is always regenerated by this module - never typed by hand.

    python3 -m engine.store data/charts/tanzil_1996-11-24.json            # refresh in place
    python3 -m engine.store data/charts/x.json --time 09:30 --sex F       # when the file's own fields are free text

Schema of "computed" (schema_version 2):
    schema_version, generated, engine{backend, ayanamsa}, birth{date,time,lat,lon,tz},
    lagna{rashi,deg,nakshatra,d9,d10,d7}, planets{name:{rashi,deg,nakshatra,pada,house,dignity,retro,combust,d9}},
    panchanga, karakas, arudhas{AL,UL,A7,A10}, sav_by_house, yogas[names], doshas,
    vimshottari{maha:[{lord,start,end}], antar_current_and_next:[{md,ad,start,end}]},
    sade_sati[[start,end]], shadbala{planet:{rupas,ratio,rank,ratio_text,rank_text}} (when engine.shadbala runs),
    classical{vimshopaka, rays_total, special_lagnas, states, moods, argala_unobstructed, gulika, spouse_direction,
              birth_conditions}  (schema 4: quantities from the Sanskrit readings of 12 Nov 2026)
"""
from __future__ import annotations
import json, sys, datetime as dt, argparse

from engine.report import build

SCHEMA_VERSION = 4


def _d(x):
    return x.isoformat()[:10] if hasattr(x, "isoformat") else str(x)[:10]


def computed(date, time, lat, lon, tz="Asia/Kolkata", sex=None):
    r = build(date, time, float(lat), float(lon), tz, sex=sex)
    c, a = r["chart"], r["analysis"]
    lg = c["lagna"]
    planets = {}
    for n, p in c["planets"].items():
        planets[n] = {"rashi": p["rashi_name"], "deg": p["deg_dms"], "nakshatra": p["nakshatra"], "pada": p["pada"],
                      "house": p["bhava"], "dignity": p.get("dignity"), "retro": bool(p.get("retrograde")),
                      "combust": bool(p.get("combust")), "d9": p["D9"]}
    today = r["today"]
    maha, antar = [], []
    for m in c["dasha"]["maha"]:
        maha.append({"lord": m["lord"], "start": _d(m["start"]), "end": _d(m["end"])})
        if _d(m["end"]) >= today.isoformat() and len(antar) < 18:        # running MD and the next one
            for ad in m["antar"]:
                antar.append({"md": m["lord"], "ad": ad["lord"], "start": _d(ad["start"]), "end": _d(ad["end"])})
    out = {
        "schema_version": SCHEMA_VERSION,
        "generated": today.isoformat(),
        "engine": {"backend": c["input"]["backend"], "ayanamsa_lahiri": round(c["input"]["ayanamsa_lahiri"], 5)},
        "birth": {"date": date, "time": time, "lat": float(lat), "lon": float(lon), "tz": tz},
        "lagna": {"rashi": lg["rashi_name"], "deg": lg["deg_dms"], "nakshatra": lg["nakshatra"],
                  "d9": lg["vargas"]["D9"], "d10": lg["vargas"]["D10"], "d7": lg["vargas"]["D7"]},
        "planets": planets,
        "panchanga": {k: (_d(v) if hasattr(v, "isoformat") else v) for k, v in a["panchanga"].items()
                      if k in ("tithi", "paksha", "vara", "yoga", "karana", "nakshatra", "pada", "day_birth")},
        "karakas": a["karakas"]["seven"],
        "arudhas": {k: a["arudhas"][k] for k in ("AL", "UL", "A7", "A10")},
        "sav_by_house": r["ashtakavarga"]["by_house"],
        "yogas": [y["name"] for y in a["yogas"]],
        "doshas": json.loads(json.dumps(a["doshas"], default=str)),
        "vimshottari": {"maha": maha, "antar_current_and_next": antar},
        "sade_sati": [[_d(s), _d(e)] for s, e in r["sade_sati"]],
    }
    out["yogini"] = [{"yogini": y["yogini"], "lord": y["lord"], "start": _d(y["start"]), "end": _d(y["end"])} for y in r["yogini"][:10]]
    out["chara"] = [{"sign": m["sign"], "years": m["years"], "start": _d(m["start"]), "end": _d(m["end"])} for m in r["chara"]["maha"]]
    out["kp"] = {"cusp_sub_lords": {str(h): c["sub"] for h, c in r["kp"]["cusps"].items()}, "planet_significations": r["kp"]["planet_significations"]}
    out["chalit_shifted"] = {p: list(x) for p, x in r["chalit"]["shifted"].items()}
    sb = r.get("shadbala")
    if sb and "planets" in sb:
        out["shadbala"] = {p: {k: (round(v[k], 2) if isinstance(v[k], float) else v[k]) for k in ("rupas", "ratio", "rank", "ratio_text", "rank_text") if k in v}
                           for p, v in sb["planets"].items() if isinstance(v, dict)}
        out["shadbala_note"] = "ratio_text / rank_text use the Sun's required 6.5 rupas of BPHS 27.32-33 and Jataka Parijata 2.40; ratio / rank are as AstroSage prints them"
    try:                                                     # quantities taken from the Sanskrit readings (schema 4)
        from engine import classical as _K, rashmi as _R, parashara_extra as _X
        ns, mo, ag, ug = _X.nine_states(c), _X.six_moods(c), _X.argala(c), _X.upagrahas(c)
        sl = _K.special_lagnas(c)
        out["classical"] = {
            "vimshopaka": {p: x["points"] for p, x in _K.vimshopaka(c).items()},
            "rays_total": _R.rashmi(c)["total"],
            "special_lagnas": {k: sl[k]["sign_name"] for k in ("bhava_lagna", "hora_lagna", "ghati_lagna")},
            "states": {p: [ns[p]["state"]] + ns[p]["also"] for p in ns},
            "moods": {p: mo[p]["moods"] for p in mo},
            "argala_unobstructed": {str(h): ag[h]["planets"] for h in range(1, 13)},
            "gulika": {"parashara_start": ug["gulika_group"]["Gulika"]["at_start"]["sign_name"],
                       "parashara_end": ug["gulika_group"]["Gulika"]["at_end"]["sign_name"],
                       "mandi_phaladeepika": ug["mandi_group_pd"]["Mandi"]["sign_name"]},
            "spouse_direction": _K.spouse_direction(c),
            "birth_conditions": _K.birth_conditions(c)["conditions"],
        }
    except Exception as e:                                   # noqa: BLE001
        out["classical"] = {"error": str(e)}
    return out


def _coord(x):
    """15.33 | '15.3333' | '30N16' | '97W44' -> signed decimal degrees."""
    try:
        return float(x)
    except (TypeError, ValueError):
        import re
        m = re.match(r"\s*(\d+)\s*([NSEW])\s*(\d+)?", str(x).upper())
        v = int(m.group(1)) + int(m.group(3) or 0) / 60
        return -v if m.group(2) in "SW" else v


def birth_of(d):
    """Birth data from any of the historical file layouts -> (date, time, lat, lon, tz, sex)."""
    b = d.get("birth") or d.get("input") or d.get("meta") or {}
    g = lambda *ks: next((x[k] for x in (d, b) for k in ks if isinstance(x, dict) and x.get(k) not in (None, "")), None)
    tz = str(g("tz") or "Asia/Kolkata").split()[0]
    return (str(g("date", "dob"))[:10], str(g("time", "tob"))[:5], _coord(g("lat")), _coord(g("lon")), tz, g("sex"))


def refresh(path, time=None, sex=None, drop=()):
    d = json.load(open(path))
    date, t0, lat, lon, tz, sx = birth_of(d)
    d["computed"] = computed(date, time or t0, lat, lon, tz, sex or sx)
    for k in drop:
        d.pop(k, None)
    json.dump(d, open(path, "w"), indent=1, ensure_ascii=False)
    return d


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("path"); ap.add_argument("--time"); ap.add_argument("--sex")
    ap.add_argument("--drop", nargs="*", default=[])
    x = ap.parse_args()
    d = refresh(x.path, x.time, x.sex, x.drop)
    print("refreshed", x.path, "| lagna", d["computed"]["lagna"]["rashi"], d["computed"]["lagna"]["deg"])
